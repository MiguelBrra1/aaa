#!/usr/bin/env python3
"""HoneyEngine branding: builds the editor's logo header and icons from one PNG.

    python3 tools/honey_assets.py

Reads editor/resources/icons/honeyengine-logo.png (transparent background) and writes:
  - editor/resources/icons/jasperengine-logo_png.h  (the loading screen and About logo;
    same symbol names, so the code that includes it does not change)
  - editor/resources/icons/jasperengine-editor.ico and jasperengine-editor-cmd.ico
    (the .exe and window icon: the logo centred on a square, 16 to 256 px)
Needs Pillow (pip install pillow). The Windows build runs it before configuring.
"""
import io
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, "editor", "resources", "icons")
SOURCE = os.path.join(ICONS, "honeyengine-logo.png")


def write_header(png_bytes):
    lines = [
        "// Generated by tools/honey_assets.py from honeyengine-logo.png: do not edit.",
        "// SPDX-License-Identifier: MIT",
        "",
        "#pragma once",
        "",
        "inline unsigned char jasperengine_logo_png[] = {",
    ]
    for i in range(0, len(png_bytes), 12):
        chunk = png_bytes[i:i + 12]
        lines.append("  " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    lines.append("inline unsigned int jasperengine_logo_png_len = %d;" % len(png_bytes))
    with open(os.path.join(ICONS, "jasperengine-logo_png.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def main():
    logo = Image.open(SOURCE).convert("RGBA")

    # the loading screen draws it 150 dpi-px wide: 2x that keeps it sharp on high-DPI screens
    width = min(logo.width, 300)
    splash = logo.resize((width, round(logo.height * width / logo.width)), Image.LANCZOS)
    buf = io.BytesIO()
    splash.save(buf, format="PNG", optimize=True)
    write_header(buf.getvalue())

    # icon: the logo centred on a transparent square
    side = max(logo.width, logo.height)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.alpha_composite(logo, ((side - logo.width) // 2, (side - logo.height) // 2))
    square = square.resize((256, 256), Image.LANCZOS)
    sizes = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]
    for name in ("jasperengine-editor.ico", "jasperengine-editor-cmd.ico"):
        square.save(os.path.join(ICONS, name), format="ICO", sizes=sizes)

    print("HoneyEngine logo: header %d bytes, icons %s" % (len(buf.getvalue()), [s[0] for s in sizes]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
