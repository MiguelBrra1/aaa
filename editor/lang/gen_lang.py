#!/usr/bin/env python3
"""Generates editor/lang/EditorLangTables.inc from the <code>.tsv files beside it.

Run after editing a .tsv:  python3 editor/lang/gen_lang.py
Each .tsv line is `English<TAB>Translation`; `#` lines are comments. The English text is the
visible part of an ImGui label (without its `##id`), matched exactly.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def cstr(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\x%02x\"\"" % ch)   # split so the next char is not read as hex
    return '"' + "".join(out) + '"'


def main():
    langs = sorted(f[:-4] for f in os.listdir(HERE) if f.endswith(".tsv"))
    lines = ["// Generated by editor/lang/gen_lang.py from editor/lang/*.tsv: do not edit.", ""]
    names = []
    for lang in langs:
        seen = {}
        for n, raw in enumerate(open(os.path.join(HERE, lang + ".tsv"), encoding="utf-8"), 1):
            raw = raw.rstrip("\n").rstrip("\r")
            if not raw or raw.startswith("#"):
                continue
            parts = raw.split("\t")
            if len(parts) != 2 or not parts[0] or not parts[1]:
                sys.exit("%s.tsv:%d: expected 'English<TAB>translation'" % (lang, n))
            if parts[0] in seen:
                print("%s.tsv:%d: '%s' repeated (line %d wins)" % (lang, n, parts[0], seen[parts[0]][0]))
                continue
            seen[parts[0]] = (n, parts[1])
        ident = "kEditorLang_" + lang.replace("-", "_")
        names.append((lang, ident, len(seen)))
        lines.append("static const EditorLangEntry %s[] = {" % ident)
        for en, (_, tr) in seen.items():
            lines.append("    {%s, %s}," % (cstr(en), cstr(tr)))
        lines.append("};")
        lines.append("")
    lines.append("static const EditorLangTable kEditorLangTables[] = {")
    for lang, ident, count in names:
        lines.append("    {%s, %s, %d}," % (cstr(lang), ident, count))
    lines.append("};")
    open(os.path.join(HERE, "EditorLangTables.inc"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    for lang, _, count in names:
        print("%s: %d texts" % (lang, count))


if __name__ == "__main__":
    main()
